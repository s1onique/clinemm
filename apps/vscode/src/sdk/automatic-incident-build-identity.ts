/**
 * ACT-CLINEMM-AUTOMATIC-INCIDENT-CAPTURE-AND-EXPORT01 (AICE01)
 *
 * The exact build and runtime identity of the code that captured the
 * incident.
 *
 * WHY THIS EXISTS
 * ---------------
 *
 * The 2026-11-05 LIVE incident reported a version string that did not
 * uniquely distinguish the installed builds. A support engineer could
 * not tell whether the running extension was the repaired build. This
 * module closes that gap.
 *
 * HONESTY CONTRACT
 * ----------------
 *
 *   - An UNAVAILABLE build identity is reported as `UNOBSERVED`. It is
 *     NEVER promoted to `VERIFIED`.
 *   - The on-disk bundle hash is the hash of the bytes ON DISK. It is
 *     NOT proof that those exact bytes are the ones already executing
 *     in memory.
 *   - The build identity describes the code that was PACKAGED, not the
 *     repository's current HEAD at some later time.
 *   - A self-referential bundle hash is never created.
 */

import { createHash } from "node:crypto"
import { readFile } from "node:fs/promises"
import { join } from "node:path"

/**
 * The build provenance artifact's schema version.
 */
export const BUILD_PROVENANCE_SCHEMA_VERSION = 1

/**
 * The file name of the generated build-provenance artifact, relative to
 * the extension root. It is UNTRACKED — the packaging pipeline
 * generates it from the committed source.
 */
export const BUILD_PROVENANCE_FILE = "build-provenance.json"

/**
 * The build-time provenance, as generated by the packaging pipeline.
 */
export interface BuildProvenance {
	readonly schemaVersion: number
	readonly sourceHead?: string
	readonly sourceTree?: string
	readonly extensionVersion?: string
	readonly buildTimestamp?: string
	readonly buildId?: string
	readonly bundledExtensionSha256?: string
	/** The exact source package manifest bound into the packaged build. */
	readonly sourcePackageSha256?: string
	/** The exact source package manifest size bound into the packaged build. */
	readonly sourcePackageBytes?: number
	/** The source package manifest path recorded in the build workspace. */
	readonly sourcePackagePath?: string
}

/**
 * The runtime identity, captured at extension activation.
 */
export interface RuntimeIdentity {
	readonly runtimeInstanceId: string
	readonly extensionVersion?: string
	readonly hostPlatform: string
	readonly hostArchitecture: string
	/** The SHA-256 of `dist/extension.js` as read from disk. */
	readonly onDiskBundleSha256?: string
}

/**
 * The verification status of the build provenance.
 */
export type BuildProvenanceVerification = "VERIFIED" | "MISMATCH" | "UNOBSERVED"

/**
 * The complete build/runtime identity block.
 */
export interface BuildRuntimeIdentity {
	readonly schemaVersion: number
	readonly provenanceVerification: BuildProvenanceVerification
	readonly build?: BuildProvenance
	readonly runtime?: RuntimeIdentity
	/** Why the verification is not `VERIFIED`. */
	readonly verificationNote?: string
}

/**
 * The SHA-256 of a file's bytes.
 */
export async function sha256File(path: string): Promise<string | undefined> {
	try {
		const contents = await readFile(path)
		return createHash("sha256").update(contents).digest("hex")
	} catch {
		return undefined
	}
}

/**
 * Read the installed extension's package manifest version.
 *
 * Returns `undefined` when the manifest is absent, unreadable, or has no
 * version string. This is an independent installed-manifest observation,
 * never inferred from the compiled runtime.
 */
export async function readInstalledPackageVersion(extensionPath: string): Promise<string | undefined> {
	try {
		const raw = await readFile(join(extensionPath, "package.json"), "utf8")
		const parsed = JSON.parse(raw) as { readonly version?: unknown }
		return typeof parsed.version === "string" && parsed.version ? parsed.version : undefined
	} catch {
		return undefined
	}
}

/**
 * Read the build provenance artifact from the extension root.
 *
 * Returns `undefined` when the artifact is absent or unreadable — an
 * absent artifact is `UNOBSERVED`, never `VERIFIED`.
 */
export async function readBuildProvenance(extensionPath: string): Promise<BuildProvenance | undefined> {
	try {
		const raw = await readFile(join(extensionPath, BUILD_PROVENANCE_FILE), "utf8")
		const parsed = JSON.parse(raw) as BuildProvenance
		if (!parsed || typeof parsed !== "object") {
			return undefined
		}
		return parsed
	} catch {
		return undefined
	}
}

/**
 * The SHA-256 of the INSTALLED bundle on disk.
 */
export async function readOnDiskBundleSha256(extensionPath: string): Promise<string | undefined> {
	return sha256File(join(extensionPath, "dist", "extension.js"))
}

/**
 * Verify the build provenance against the runtime identity.
 *
 * The rules:
 *
 *   - NO build provenance at all → `UNOBSERVED`.
 *   - A provenance whose `bundledExtensionSha256` differs from the
 *     ON-DISK bundle hash → `MISMATCH` (the installed bytes are not
 *     the bytes the provenance describes).
 *   - A provenance WITH a matching `bundledExtensionSha256` but no
 *     on-disk bundle to compare against → `UNOBSERVED` (there is
 *     nothing to verify against).
 *   - A provenance with a matching hash → `VERIFIED`.
 */
export function verifyBuildProvenance(
	provenance: BuildProvenance | undefined,
	onDiskBundleSha256: string | undefined,
	options?: {
		readonly runtimeExtensionVersion?: string
		readonly installedPackageVersion?: string
	},
): { readonly verification: BuildProvenanceVerification; readonly note?: string } {
	if (!provenance) {
		return { verification: "UNOBSERVED", note: "no build provenance artifact was present" }
	}
	if (!provenance.bundledExtensionSha256) {
		return { verification: "UNOBSERVED", note: "the build provenance does not carry a bundled extension hash" }
	}
	if (!onDiskBundleSha256) {
		return {
			verification: "UNOBSERVED",
			note: "the on-disk extension bundle could not be read, so the provenance could not be verified",
		}
	}
	if (provenance.bundledExtensionSha256 !== onDiskBundleSha256) {
		return {
			verification: "MISMATCH",
			note: "the on-disk extension bundle hash does not match the packaged build provenance",
		}
	}
	const runtimeVersion = options?.runtimeExtensionVersion
	const installedVersion = options?.installedPackageVersion
	if (runtimeVersion && installedVersion && runtimeVersion !== installedVersion) {
		return {
			verification: "MISMATCH",
			note: "the runtime extension version does not match the installed package manifest version",
		}
	}
	if (provenance.extensionVersion && runtimeVersion && provenance.extensionVersion !== runtimeVersion) {
		return {
			verification: "MISMATCH",
			note: "the packaged build version does not match the runtime extension version",
		}
	}
	if (provenance.extensionVersion && installedVersion && provenance.extensionVersion !== installedVersion) {
		return {
			verification: "MISMATCH",
			note: "the packaged build version does not match the installed package manifest version",
		}
	}
	return { verification: "VERIFIED" }
}

/**
 * Build the complete build/runtime identity block.
 */
export function buildBuildRuntimeIdentity(input: {
	readonly provenance?: BuildProvenance
	readonly runtime: RuntimeIdentity
	readonly installedPackageVersion?: string
}): BuildRuntimeIdentity {
	const { verification, note } = verifyBuildProvenance(input.provenance, input.runtime.onDiskBundleSha256, {
		runtimeExtensionVersion: input.runtime.extensionVersion,
		installedPackageVersion: input.installedPackageVersion,
	})
	return {
		schemaVersion: BUILD_PROVENANCE_SCHEMA_VERSION,
		provenanceVerification: verification,
		...(input.provenance ? { build: input.provenance } : {}),
		runtime: input.runtime,
		...(note ? { verificationNote: note } : {}),
	}
}
