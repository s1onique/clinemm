/**
 * Whether two mechanisms are the SAME mechanism.
 *
 * It is a named function rather than a string comparison at each call site,
 * because the whole point is that the names must NOT be used
 * interchangeably.
 */
export function isSameEvidenceMechanism(
	left: EvidenceMechanism,
	right: EvidenceMechanism,
): boolean {
	return left === right;
}

/**
 * Whether a mechanism preserves the ORIGINAL bytes.
 */
export function preservesOriginalBytes(mechanism: EvidenceMechanism): boolean {
	return EVIDENCE_MECHANISM_PROPERTIES[mechanism].preservesOriginalBytes;
}

/**
 * Whether a mechanism can introduce a factual SUBSTITUTION.
 */
export function canDistortFacts(mechanism: EvidenceMechanism): boolean {
	return EVIDENCE_MECHANISM_PROPERTIES[mechanism].canDistortFacts;
}

/**
 * The ADDITIONAL inference requests a mechanism consumes.
 *
 * Every mechanism in this vocabulary consumes ZERO: none of them adds a
 * request to the summarizer's single request.
 */
export function additionalInferenceRequests(
	mechanism: EvidenceMechanism,
): number {
	return EVIDENCE_MECHANISM_PROPERTIES[mechanism].additionalInferenceRequests;
}
