/**
 * ACT-CLINEMM-COMPACTION-FACTUAL-PRESERVATION-REPAIR-01
 *
 * C3 — THE EVIDENCE IDENTITY VOCABULARY.
 *
 * ============================================================================
 * WHY THIS EXISTS
 * ============================================================================
 *
 * The predecessor ACTs measured FOUR different things and reported them
 * under overlapping names. They are NOT the same mechanism, they do NOT have
 * the same cost, and they do NOT have the same failure modes. A report that
 * conflates them cannot be read.
 *
 * The distinctions that matter:
 *
 *   | Mechanism                              | Who writes the bytes | Cost          |
 *   | -------------------------------------- | -------------------- | ------------- |
 *   | TARGETED_ORIGINAL_EVIDENCE_RESTORATION | none (original)      | full fragment |
 *   | MINIMAL_BOUNDED_RESTORATION            | none (original)      | smallest set  |
 *   | EVIDENCE_ENHANCED_SUMMARIZATION        | THE MODEL            | one request   |
 *   | DETERMINISTIC_EVIDENCE_CARRY_FORWARD   | none (original)      | one section   |
 *
 * The decisive difference is the SECOND column. Three of the four preserve
 * the ORIGINAL bytes; one asks the model to REGENERATE them, and only that
 * one can introduce a factual substitution.
 *
 * ============================================================================
 * THE CONFUSION THIS VOCABULARY PREVENTS
 * ============================================================================
 *
 * "Targeted restoration improved O4 and O7" is TRUE of
 * TARGETED_ORIGINAL_EVIDENCE_RESTORATION and is NOT a statement about
 * EVIDENCE_ENHANCED_SUMMARIZATION, which did NOT flip either item. A report
 * that says "evidence restoration works" without naming the mechanism has
 * established nothing.
 */

/**
 * The MECHANISM by which evidence reached a context.
 */
export type EvidenceMechanism =
	/**
	 * The ORIGINAL evidence fragment was placed into the context, unaltered.
	 *
	 * The bytes are the tool's own output. No model wrote them, so no model
	 * can have distorted them. The cost is the fragment's own size.
	 */
	| "TARGETED_ORIGINAL_EVIDENCE_RESTORATION"
	/**
	 * The SMALLEST set of original evidence fragments that could resolve the
	 * question, placed into the context unaltered.
	 *
	 * It differs from TARGETED_ORIGINAL_EVIDENCE_RESTORATION in the SIZE of
	 * the restored set, not in its nature. A "targeted restoration" that
	 * restores 35 000 characters is targeted but not minimal.
	 */
	| "MINIMAL_BOUNDED_RESTORATION"
	/**
	 * The evidence was placed into the SUMMARIZER's input, and the MODEL
	 * regenerated it as prose.
	 *
	 * This is the ONLY mechanism that can introduce a factual substitution,
	 * because it is the only one in which a model rewrites the observation.
	 */
	| "EVIDENCE_ENHANCED_SUMMARIZATION"
	/**
	 * The ORIGINAL evidence fragment was carried into the context by the
	 * runtime's own deterministic mechanism, without the model's
	 * participation.
	 *
	 * It is idempotent, boundary-stable, and cannot be distorted.
	 */
	| "DETERMINISTIC_EVIDENCE_CARRY_FORWARD";

/**
 * The PROPERTIES of a mechanism, as they bear on the decision.
 */
export interface EvidenceMechanismProperties {
	readonly mechanism: EvidenceMechanism;
	/**
	 * Whether the ORIGINAL bytes reach the context.
	 *
	 * `false` means the bytes were REGENERATED by the model, and therefore
	 * subject to factual substitution.
	 */
	readonly preservesOriginalBytes: boolean;
	/**
	 * Whether the mechanism can introduce a factual SUBSTITUTION.
	 */
	readonly canDistortFacts: boolean;
	/**
	 * Whether the mechanism consumes an ADDITIONAL inference request.
	 */
	readonly additionalInferenceRequests: number;
	/**
	 * Whether the mechanism's cost grows with the transcript.
	 *
	 * `false` means the cost is bounded by a fixed per-item or per-request
	 * budget.
	 */
	readonly costGrowsWithTranscript: boolean;
	/**
	 * Whether the mechanism is IDEMPOTENT — a second application replaces
	 * rather than accumulates.
	 */
	readonly idempotent: boolean;
}

